/** Icon of each nav destination, by NavLink key (lib/workspace/access.ts SHEETS and OWNER_PAGES). */
const NAV_ICONS: Record<string, IconName> = {
  dashboard: "home",
  laporan: "report",
  performa: "assessment",
  bmi: "scale",
  remedial: "training",
  tindakLanjut: "followUp",
  sdm: "people",
  penggantian: "swap",
  tautan: "link",
  akun: "idCard",
  pengaturan: "parameters",
  sinkronisasi: "sync",
};

export function navIconName(key: string): IconName {
  return NAV_ICONS[key] ?? "report";
}

/** A shell icon at `size` px (20 in nav rows, 16 in caption lines). Colour follows currentColor. */
export function Icon({ name, size = 20, className }: { name: IconName; size?: 16 | 18 | 20; className?: string }) {
  return (
    <svg
      aria-hidden="true"
      focusable="false"
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={1.75}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className}
    >
      {PATHS[name]}
    </svg>
  );
}
