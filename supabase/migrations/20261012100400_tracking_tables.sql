-- Raw-input tracking tables. Derived values (final result, statuses, BMI, flags) are computed in
-- lib/rules.ts, never stored. Every table records updated_by_link (stamped server-side).

-- ---------------------------------------------------------------- staff (sheet "Master SDM")
create table public.staff (
  code              text primary key,
  program           text,
  provider          text,
  station           text not null references public.stations (code) on update cascade,
  name              text not null,
  employee_no       text,
  gender            text,
  touch_point       text,
  role_play         numeric,
  post_test         numeric,
  report_remark     text,
  assignment_status text not null default 'Aktif',
  feedback          text,
  notes             text,
  bmi_has_note      boolean,
  bmi_note          text,
  sort_order        integer,
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now(),
  updated_by_link   uuid references public.share_links (id) on delete set null,
  constraint staff_code_check check (code <> '' and code = btrim(code)),
  constraint staff_name_check check (btrim(name) <> ''),
  constraint staff_program_check check (program in ('IULS', 'RUST')),
  constraint staff_gender_check check (gender in ('L', 'P')),
  constraint staff_touch_point_check check (
    touch_point in ('Check-in Counter', 'Customer Service', 'Boarding Gate', 'Transfer Desk', 'Baggage Service')
  ),
  constraint staff_role_play_check check (role_play between 0 and 100),
  constraint staff_post_test_check check (post_test between 0 and 100),
  constraint staff_report_remark_check check (report_remark in ('Passed', 'Failed')),
  constraint staff_assignment_status_check check (
    assignment_status in ('Aktif', 'Remedial', 'Individual Coaching', 'Ditarik dari layanan')
  )
);

create index staff_station_idx on public.staff (station);
create index staff_updated_by_link_idx on public.staff (updated_by_link);

create trigger staff_set_updated_at
  before insert or update on public.staff
  for each row execute function private.set_updated_at();

create trigger staff_stamp_link
  before insert or update on public.staff
  for each row execute function private.stamp_link_attribution();


-- ---------------------------------------------------------------- weekly_scores (sheet "Log Performa Mingguan")
create table public.weekly_scores (
  id                  bigint generated by default as identity primary key,
  staff_code          text not null references public.staff (code) on delete cascade on update cascade,
  week                smallint not null,
  touch_point         text,
  score_grooming      numeric,
  score_knowledge     numeric,
  score_attitude      numeric,
  score_communication numeric,
  gap_topic           text,
  observer            text,
  coaching_notes      text,
  updated_at          timestamptz not null default now(),
  updated_by          uuid references auth.users (id) on delete set null,
  updated_by_link     uuid references public.share_links (id) on delete set null,
  constraint weekly_scores_staff_week_key unique (staff_code, week),
  constraint weekly_scores_week_check check (week between 1 and 20),
  constraint weekly_scores_touch_point_check check (
    touch_point in ('Check-in Counter', 'Customer Service', 'Boarding Gate', 'Transfer Desk', 'Baggage Service')
  ),
  constraint weekly_scores_score_grooming_check check (score_grooming between 0 and 100),
  constraint weekly_scores_score_knowledge_check check (score_knowledge between 0 and 100),
  constraint weekly_scores_score_attitude_check check (score_attitude between 0 and 100),
  constraint weekly_scores_score_communication_check check (score_communication between 0 and 100)
);

create index weekly_scores_updated_by_idx on public.weekly_scores (updated_by);
create index weekly_scores_updated_by_link_idx on public.weekly_scores (updated_by_link);

-- link write -> updated_by_link = link, updated_by = NULL;
-- otherwise  -> updated_by = auth.uid() (NULL for service role / SQL), updated_by_link = NULL.
create or replace function private.stamp_weekly_score_author()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  v_link uuid := nullif(pg_catalog.current_setting('tracker.share_link_id', true), '')::uuid;
begin
  new.updated_by_link := v_link;
  new.updated_by := case when v_link is null then auth.uid() end;
  return new;
end;
$$;

revoke all on function private.stamp_weekly_score_author() from public, anon, authenticated;

create trigger weekly_scores_set_updated_at
  before insert or update on public.weekly_scores
  for each row execute function private.set_updated_at();

create trigger weekly_scores_stamp_author
  before insert or update on public.weekly_scores
  for each row execute function private.stamp_weekly_score_author();


